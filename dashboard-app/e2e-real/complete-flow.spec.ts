import { test, expect, type Page } from '@playwright/test';

async function login(page: Page, role: string, path: string) {
  await page.goto(path);
  await page.locator('input[type="email"]').fill(`${role}@local.pulse-epis.test`);
  await page.locator('input[type="password"]').fill('pulse-local-demo');
  await page.locator('form button[type="submit"]').click();
  await expect(page.getByRole('button', { name: 'Cerrar sesión' })).toBeVisible();
}

test('evidencia, validación, perfil, oportunidad y participación con API real', async ({ browser }) => {
  const adminContext = await browser.newContext();
  const studentContext = await browser.newContext();
  const validatorContext = await browser.newContext();
  const admin = await adminContext.newPage();
  const student = await studentContext.newPage();
  const validator = await validatorContext.newPage();
  await login(admin, 'admin', '/admin/radar');
  // Catalog prerequisites have no authoring screen; create only these via real API.
  const interestResponse = await adminContext.request.post('http://127.0.0.1:8080/api/v1/learning/interests', { data: { name: 'IA sintética' } });
  expect(interestResponse.status()).toBe(201);
  await interestResponse.json();
  const routeResponse = await adminContext.request.post('http://127.0.0.1:8080/api/v1/learning/routes', { data: { title: 'Ruta sintética', description: 'Ruta de aceptación con datos ficticios', steps: [{ title: 'Fundamentos de Python', skills: ['Python'], prerequisites: [] }] } });
  expect(routeResponse.status()).toBe(201);
  const route = await routeResponse.json();
  const publication = await adminContext.request.post(`http://127.0.0.1:8080/api/v1/learning/routes/${route.id}/status`, { data: { status: 'PUBLISHED', reason: 'Ruta sintética revisada para aceptación.' } });
  expect(publication.ok()).toBeTruthy();
  await login(student, 'student', '/mi-perfil');
  await student.getByRole('button', { name: 'Nueva certificación', exact: true }).click();
  await student.getByLabel('Nombre de la certificación').fill('Python sintético');
  await student.getByLabel('Entidad emisora').fill('Emisor sintético');
  await student.getByLabel('Fecha de emisión', { exact: true }).fill('2026-09-01');
  await student.getByLabel('Habilidades, separadas por comas').fill('Python');
  await student.locator('input[type="file"]').setInputFiles({ name: 'evidencia-demo.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4\nsynthetic evidence\n%%EOF') });
  await student.getByRole('button', { name: 'Enviar a validación' }).click();
  await expect(student.getByText('Certificación registrada.', { exact: false })).toBeVisible();
  await login(validator, 'validator', '/validaciones');
  await validator.getByRole('button', { name: /Python sintético.*Ver envío/ }).click();
  await validator.getByRole('button', { name: 'Tomar revisión' }).click();
  await validator.getByRole('button', { name: 'Aprobar', exact: true }).click();
  await student.reload();
  await expect(student.getByRole('article', { name: 'Aprobadas: 1' })).toBeVisible();
  await student.screenshot({ path: '../docs/recursos/imagenes/va80-browser-certification.png', fullPage: true });
  await student.goto('/mi-ruta');
  await student.locator('fieldset').first().getByText('IA sintética', { exact: true }).click();
  await expect(student.getByLabel('IA sintética', { exact: true })).toBeChecked();
  await student.getByLabel('Ruta de formación').selectOption(route.id);
  await student.getByRole('button', { name: 'Guardar preferencias' }).click();
  await expect(student.getByRole('status').filter({ hasText: 'Tus preferencias quedaron guardadas.' })).toBeVisible();
  await admin.reload();
  await admin.getByText('Registrar fuente de curso').click();
  await admin.getByLabel('Nombre del curso').fill('Curso sintético');
  await admin.getByLabel('Proveedor', { exact: true }).fill('Proveedor sintético');
  await admin.getByLabel('Fuente HTTPS', { exact: true }).fill('https://example.invalid/course');
  await admin.getByLabel('Habilidades (separadas por coma)').fill('Python');
  await admin.getByRole('button', { name: 'Registrar para revisión' }).click();
  await admin.getByRole('button', { name: 'Iniciar revisión' }).click();
  await admin.getByLabel('Título de la oportunidad').fill('Oportunidad sintética');
  await admin.getByLabel('IA sintética', { exact: true }).check();
  await admin.getByLabel('Explicación de relevancia').fill('Formación sintética para profundizar habilidades de Python.');
  await admin.getByRole('button', { name: 'Guardar y publicar' }).click();
  await expect(admin.getByRole('status').filter({ hasText: 'Oportunidad publicada' })).toBeVisible();
  await admin.evaluate(() => { document.documentElement.style.scrollBehavior = 'auto'; window.scrollTo(0, 0); });
  await admin.waitForFunction(() => window.scrollY === 0);
  await admin.screenshot({ path: '../docs/recursos/imagenes/va80-browser-opportunity.png', fullPage: true });
  await admin.goto('/talleres');
  await admin.getByLabel('Oportunidad publicada').selectOption({ label: 'Oportunidad sintética' });
  await admin.getByLabel('Nombre del taller').fill('Taller sintético');
  await admin.getByLabel('Capacidad', { exact: true }).fill('1');
  await admin.getByRole('button', { name: 'Crear y abrir taller' }).click();
  await student.goto('/talleres');
  await student.getByRole('checkbox').check();
  await student.getByRole('button', { name: 'Enviar solicitud' }).click();
  await expect(student.getByRole('status').filter({ hasText: 'Tu solicitud quedó registrada' })).toBeVisible();
  await admin.reload();
  await admin.getByLabel('Motivo de decisión (mínimo 10 caracteres)').fill('Requisitos sintéticos revisados en aceptación.');
  await admin.getByRole('button', { name: 'Aceptar', exact: true }).click();
  await studentContext.close();
  const returningContext = await browser.newContext();
  const returning = await returningContext.newPage();
  await login(returning, 'student', '/talleres');
  await expect(returning.getByRole('region', { name: 'Mis solicitudes' }).getByText('Aceptada', { exact: true })).toBeVisible();
  await expect(returning.getByRole('region', { name: 'Mis solicitudes' }).getByText('Motivo registrado: Requisitos sintéticos revisados en aceptación.', { exact: true })).toBeVisible();
  const persistedWorkshops = await returningContext.request.get('http://127.0.0.1:8080/api/v1/learning/workshops');
  expect(persistedWorkshops.ok()).toBeTruthy();
  expect((await persistedWorkshops.json())[0].available_places).toBe(0);
  await returning.screenshot({ path: '../docs/recursos/imagenes/va80-browser-participation.png', fullPage: true });
  await returning.goto('/mi-ruta');
  await expect(returning.getByLabel('Ruta de formación')).toHaveValue(route.id);
  await returning.screenshot({ path: '../docs/recursos/imagenes/va80-browser-profile.png', fullPage: true });
  await adminContext.close();
  await validatorContext.close();
  await returningContext.close();
});
